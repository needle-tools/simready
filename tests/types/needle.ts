import {type Context,type Rigidbody,type Collider} from '@needle-tools/engine';
import {createNeedleSimulationWorld,type NeedleSimulationAsset} from '@needle-tools/simready/needle';
import {type PhysicsSnapshot} from '@needle-tools/simready';
import {type SimreadyRuntime} from '@needle-tools/simready/gltf';
declare const context:Context,snapshot:PhysicsSnapshot,runtime:SimreadyRuntime;
const host=await createNeedleSimulationWorld({context});
const backend:string=host.capabilities.backend;
const asset=await host.addAsset({snapshot});
const component:Rigidbody|undefined=asset.rigidbodies.get('/Body');
const collider:Collider|undefined=asset.colliderComponents.get('/Body/Shape');
const height:number|undefined=asset.bodies.get('/Body')?.body.translation().y;
const driven:boolean|undefined=asset.joints.get('/Joint')?.setDriveTarget({position:1});
const retained:Rigidbody|undefined=host.assets.get(asset.id)?.rigidbodies.get('/Body');
const gltf=await runtime.createSimulation({world:host});
const imported:NeedleSimulationAsset=gltf;
void [backend,component,collider,height,driven,retained,imported,gltf.root];
